/**
 * Retrieve the full institutional specification for an instrument.
 * @param {string} symbolText - Symbol or user string (e.g. "EURUSD", "Boom 1000", "Gold")
 * @param {string} [marketCategory] - Optional market category override ('forex', 'crypto', etc.)
 * @returns {Object} Complete instrument specification
 */
export const getInstrumentSpec = (symbolText, marketCategory = null) => {
  const resolved = resolveSymbol(symbolText);
  const canonical = resolved?.symbol || String(symbolText || '').trim();
  const market = marketCategory || resolved?.market || 'forex';

  if (INSTRUMENT_SPECS[canonical]) {
    return { ...INSTRUMENT_SPECS[canonical] };
  }

  // Fallback to market default specs
  const defaultSpec = MARKET_DEFAULT_SPECS[market] || MARKET_DEFAULT_SPECS.forex;

  // Infer base and quote currency from standard 6-char forex pair (e.g. EURUSD -> EUR, USD)
  let quote = defaultSpec.quoteCurrency;
  let base = defaultSpec.baseCurrency;
  let pipSize = defaultSpec.pipSize;
  let precision = defaultSpec.pricePrecision;

  if (market === 'forex' && canonical.length >= 6) {
    base = canonical.slice(0, 3).toUpperCase();
    quote = canonical.slice(3, 6).toUpperCase();
    if (quote === 'JPY') {
      pipSize = 0.01;
      precision = 3;
    }
  }

  return {
    symbol: canonical || 'CUSTOM',
    label: resolved?.label || canonical || 'Custom Instrument',
    market,
    baseCurrency: base,
    quoteCurrency: quote,
    contractSize: defaultSpec.contractSize,
    pipSize,
    lotStep: defaultSpec.lotStep,
    minLot: defaultSpec.minLot,
    maxLot: defaultSpec.maxLot,
    defaultLeverage: defaultSpec.defaultLeverage,
    commissionPerLot: defaultSpec.commissionPerLot,
    pointValueMultiplier: defaultSpec.pointValueMultiplier,
    pricePrecision: precision,
  };
};
